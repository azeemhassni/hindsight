import Foundation

/// Renders and writes the managed ssh config.
public struct SSHConfiguration: Sendable {
    public let paths: SSHPaths

    public init(paths: SSHPaths) {
        self.paths = paths
    }

    public func stanza(for destination: SSHDestination) throws -> String {
        let controlPath = try paths.controlPath(forToken: destination.controlToken)
        let options: [(String, String)] = [
            ("HostName", destination.host),
            ("Port", String(destination.port)),
            ("User", destination.user),
            ("IdentityFile", destination.identityFile),
            // Never offer keys from the agent or the user's defaults: a backup
            // job must authenticate with exactly the key it was configured with.
            ("IdentitiesOnly", "yes"),
            ("IdentityAgent", "none"),
            ("UserKnownHostsFile", paths.knownHostsFile.path),
            ("GlobalKnownHostsFile", "/dev/null"),
            ("StrictHostKeyChecking", "yes"),
            ("ControlMaster", "auto"),
            ("ControlPath", controlPath),
            ("ControlPersist", "120"),
            ("ServerAliveInterval", "30"),
            ("ServerAliveCountMax", "6"),
            ("ConnectTimeout", "15"),
            // A backup must fail loudly rather than run with a dead tunnel.
            ("ExitOnForwardFailure", "yes"),
            ("BatchMode", "yes"),
            ("ForwardAgent", "no"),
            ("ForwardX11", "no"),
            ("PermitLocalCommand", "no"),
            ("RequestTTY", "no"),
        ]

        var lines = ["Host \(destination.configAlias)"]
        lines += options.map { "  \($0) \($1)" }
        return lines.joined(separator: "\n")
    }

    public func render(for destinations: [SSHDestination]) throws -> String {
        var sections = [
            "# Generated by Hindsight. Edits are overwritten.",
            "# The user's own ~/.ssh/config is never read or modified.",
        ]
        for destination in destinations.sorted(by: { $0.configAlias < $1.configAlias }) {
            sections.append(try stanza(for: destination))
        }
        return sections.joined(separator: "\n\n") + "\n"
    }

    @discardableResult
    public func write(for destinations: [SSHDestination]) throws -> URL {
        try paths.prepare()
        let contents = try render(for: destinations)
        let temporary = paths.configFile.appendingPathExtension("new")
        try Data(contents.utf8).write(to: temporary, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: temporary.path)
        _ = try FileManager.default.replaceItemAt(paths.configFile, withItemAt: temporary)
        return paths.configFile
    }
}
